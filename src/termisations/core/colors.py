"""Цвет собеседника по XEP-0392 Consistent Color Generation.

Плагина в slixmpp нет, а расширение целиком помещается в тридцать строк
арифметики: из имени берется хэш, из хэша угол, из угла координаты CbCr, из них
цвет при постоянной яркости. Смысл в том, что один и тот же участник получает
один и тот же цвет у всех клиентов, и в комнате на два десятка человек реплики
различаются без чтения ников.

Шаги следуют разделам 5.4 и 5.5 расширения. Отступать здесь нельзя ни в одном
месте: другое прочтение хэша или другая формула перевода дадут другой цвет, и
смысл расширения - совпадение с чужими клиентами - пропадет.

Тесты проверяют формулу, но не сверяют вывод с таблицей контрольных значений из
раздела 13. Окончательно совпадение с чужими клиентами подтверждает только такая
сверка.
"""

import hashlib
import math
from typing import Final

__all__ = ["LUMA", "color_of", "hue_of", "rgb_of"]

# Постоянная яркость из раздела 5.5. Из хэша она не берется: цвет обязан
# читаться и на светлом фоне, и на темном.
LUMA: Final = 0.732

# Серый для случая, когда имени нет. Исключение здесь заставило бы проверять имя
# в каждом месте отрисовки.
_NO_NAME: Final = "#808080"


def hue_of(identifier: str) -> float:
    """Угол цвета участника в радианах по разделу 5.4.

    Берутся первые два байта SHA-1 как беззнаковое целое little-endian. Именно
    так задано расширением, и любое другое прочтение даст другой цвет. Хэш здесь
    не криптографический примитив, а способ получить устойчивое число.
    """
    digest = hashlib.sha1(identifier.encode("utf-8"), usedforsecurity=False).digest()
    value = digest[0] | (digest[1] << 8)
    return value / 65536.0 * 2 * math.pi


def rgb_of(identifier: str) -> tuple[int, int, int]:
    """Составляющие цвета участника в диапазоне 0-255."""
    angle = hue_of(identifier)
    cr = math.sin(angle)
    cb = math.cos(angle)
    # Раздел 5.4: координаты приводятся так, чтобы большая по модулю равнялась
    # половине. Без этого шага цвета выходят разной насыщенности.
    factor = 0.5 / max(abs(cr), abs(cb))
    cr *= factor
    cb *= factor

    # Раздел 5.5: перевод YCbCr в RGB при постоянной яркости.
    red = LUMA + 1.402 * cr
    blue = LUMA + 1.772 * cb
    green = (LUMA - 0.2126 * red - 0.0722 * blue) / 0.7152
    return (_byte(red), _byte(green), _byte(blue))


def color_of(identifier: str) -> str:
    """Цвет участника в виде ``#rrggbb``. Пустое имя дает серый."""
    if not identifier:
        return _NO_NAME
    red, green, blue = rgb_of(identifier)
    return f"#{red:02x}{green:02x}{blue:02x}"


def _byte(value: float) -> int:
    """Составляющая цвета в диапазоне 0-255 с отсечением за границами."""
    return max(0, min(255, round(value * 255)))
